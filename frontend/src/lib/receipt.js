export function printReceipt(d) {
  const { payment, student, institute, course_title } = d || {};
  if (!payment) return;
  const inst = institute || {};
  const fmt = (n) => `₹${Number(n || 0).toLocaleString("en-IN")}`;
  const date = new Date(payment.created_at).toLocaleString("en-IN", { dateStyle: "medium", timeStyle: "short" });
  const w = window.open("", "_blank", "width=760,height=860");
  if (!w) return;
  w.document.write(`<!doctype html><html><head><title>Receipt ${payment.reference}</title>
  <meta charset="utf-8"/>
  <style>
    *{box-sizing:border-box;margin:0;padding:0;font-family:Arial,Helvetica,sans-serif}
    body{padding:40px;color:#0f172a}
    .head{display:flex;justify-content:space-between;align-items:flex-start;border-bottom:3px solid #0d9488;padding-bottom:16px}
    .brand{font-size:22px;font-weight:800}
    .muted{color:#64748b;font-size:13px}
    .title{margin-top:28px;font-size:15px;text-transform:uppercase;letter-spacing:2px;color:#0d9488;font-weight:700}
    table{width:100%;border-collapse:collapse;margin-top:16px}
    td{padding:10px 8px;border-bottom:1px solid #e2e8f0;font-size:14px}
    .label{color:#64748b;width:40%}
    .total{margin-top:24px;background:#f0fdfa;border:1px solid #99f6e4;border-radius:10px;padding:16px 20px;display:flex;justify-content:space-between;align-items:center}
    .total b{font-size:22px;color:#0f766e}
    .foot{margin-top:40px;font-size:12px;color:#94a3b8;text-align:center}
    .status{display:inline-block;padding:3px 10px;border-radius:999px;font-size:12px;font-weight:600;background:#dcfce7;color:#166534}
    @media print{body{padding:20px}}
  </style></head><body>
    <div class="head">
      <div><div class="brand">${inst.name || "EduPrime Academy"}</div><div class="muted">${inst.address || ""}</div><div class="muted">${inst.phone || ""} ${inst.email ? "· " + inst.email : ""}</div></div>
      <div style="text-align:right"><div class="muted">Receipt No.</div><div style="font-weight:700;font-family:monospace">${payment.reference}</div><div class="muted">${date}</div></div>
    </div>
    <div class="title">Fee Payment Receipt</div>
    <table>
      <tr><td class="label">Student</td><td>${student?.name || ""} (${student?.student_code || ""})</td></tr>
      <tr><td class="label">Course</td><td>${course_title || "—"}</td></tr>
      <tr><td class="label">Payment method</td><td style="text-transform:capitalize">${(payment.method || "").replace(/_/g, " ")}</td></tr>
      ${payment.payment_ref ? `<tr><td class="label">Payment reference</td><td>${payment.payment_ref}</td></tr>` : ""}
      <tr><td class="label">Recorded by</td><td>${payment.recorded_by || ""}</td></tr>
      <tr><td class="label">Status</td><td><span class="status">${payment.reversed ? "Reversed" : "Paid"}</span></td></tr>
      ${payment.note ? `<tr><td class="label">Note</td><td>${payment.note}</td></tr>` : ""}
    </table>
    <div class="total"><span>Amount ${payment.reversed ? "(reversed)" : "received"}</span><b>${fmt(payment.amount)}</b></div>
    <div class="foot">This is an offline payment record generated by ${inst.name || "EduPrime Academy"}. Computer-generated receipt — no signature required.</div>
  </body></html>`);
  w.document.close();
  w.focus();
  setTimeout(() => w.print(), 400);
}
